\echo ''
\echo '1. All products in the store'
SELECT
    product_id,
    name,
    description,
    price
FROM products
ORDER BY name;

\echo ''
\echo '2. Orders placed by user anita'
SELECT
    o.order_id,
    u.username,
    o.order_date,
    SUM(oi.quantity * p.price)::NUMERIC(12, 2) AS order_total
FROM orders AS o
JOIN users AS u ON u.user_id = o.user_id
JOIN order_items AS oi ON oi.order_id = o.order_id
JOIN products AS p ON p.product_id = oi.product_id
WHERE u.username = 'anita'
GROUP BY o.order_id, u.username, o.order_date
ORDER BY o.order_date;

\echo ''
\echo '3. Products included in each order'
SELECT
    o.order_id,
    u.username,
    p.name AS product,
    oi.quantity,
    p.price AS unit_price,
    (oi.quantity * p.price)::NUMERIC(12, 2) AS line_total
FROM order_items AS oi
JOIN orders AS o ON o.order_id = oi.order_id
JOIN users AS u ON u.user_id = o.user_id
JOIN products AS p ON p.product_id = oi.product_id
ORDER BY o.order_id, p.name;

\echo ''
\echo '4. Total revenue generated by the store'
SELECT
    SUM(oi.quantity * p.price)::NUMERIC(12, 2) AS total_revenue
FROM order_items AS oi
JOIN products AS p ON p.product_id = oi.product_id;
